// Starts the whole local environment from scratch and is safe to run again: checks Docker,
// installs dependencies if missing, starts the local Supabase stack, writes .env.local from
// `supabase status` if it does not exist, and runs `pnpm dev`.
// SUPABASE_DB_PASSWORD (the production password) is removed, as in scripts/supabase-local.mjs.
import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const env = { ...process.env };
delete env.SUPABASE_DB_PASSWORD;
const shell = process.platform === "win32";

function run(command, args, options = {}) {
  return spawnSync(command, args, { env, shell, stdio: "inherit", ...options });
}

function fail(message) {
  console.error(`\n${message}`);
  process.exit(1);
}

if (run("docker", ["info"], { stdio: "ignore" }).status !== 0) {
  fail("Docker is not running. Start Docker Desktop and run `pnpm local` again.");
}

if (!existsSync("node_modules")) {
  if (run("pnpm", ["install"]).status !== 0) fail("pnpm install failed.");
}

if (run("pnpm", ["exec", "supabase", "status"], { stdio: "ignore" }).status !== 0) {
  if (run("pnpm", ["exec", "supabase", "start"]).status !== 0) fail("supabase start failed.");
}

if (!existsSync(".env.local")) {
  const status = run("pnpm", ["exec", "supabase", "status", "-o", "env"], { stdio: ["ignore", "pipe", "inherit"] });
  if (status.status !== 0) fail("supabase status failed.");
  const values = Object.fromEntries(
    status.stdout
      .toString()
      .split(/\r?\n/)
      .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
      .filter(Boolean)
      .map(([, key, value]) => [key, value]),
  );
  writeFileSync(
    ".env.local",
    [
      "# Generated by `pnpm local` from `supabase status`. Local values only.",
      `NEXT_PUBLIC_SUPABASE_URL=${values.API_URL}`,
      `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${values.PUBLISHABLE_KEY}`,
      "CRON_SECRET=local-cron-secret",
      `SUPABASE_DB_URL=${values.DB_URL}`,
      "",
    ].join("\n"),
  );
  console.log("Wrote .env.local");
}

console.log("\nApp: http://localhost:3000  (sign in at http://localhost:3000/dev-login)\n");
process.exit(run("pnpm", ["dev"]).status ?? 1);
